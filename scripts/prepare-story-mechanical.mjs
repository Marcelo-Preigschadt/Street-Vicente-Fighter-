function components(image){
  const cv=createCanvas(image.width,image.height),c=cv.getContext('2d');c.drawImage(image,0,0);
  const pixels=c.getImageData(0,0,image.width,image.height).data,seen=new Uint8Array(image.width*image.height),found=[];
  for(let i=0;i<seen.length;i++){
    if(seen[i]||pixels[i*4+3]<96)continue;
    const queue=[i];seen[i]=1;let cursor=0,x0=image.width,y0=image.height,x1=0,y1=0;
    while(cursor<queue.length){const n=queue[cursor++],x=n%image.width,y=Math.floor(n/image.width);x0=Math.min(x0,x);x1=Math.max(x1,x);y0=Math.min(y0,y);y1=Math.max(y1,y);
      for(const next of[n-1,n+1,n-image.width,n+image.width])if(next>=0&&next<seen.length&&!seen[next]&&pixels[next*4+3]>=96&&Math.abs(next%image.width-x)<=1){seen[next]=1;queue.push(next);}
    }
    if(queue.length>1000)found.push({pixels:queue,x0:Math.max(0,x0-7),y0:Math.max(0,y0-7),x1:Math.min(image.width,x1+8),y1:Math.min(image.height,y1+8)});
  }
  return found.sort((a,b)=>((a.y0+a.y1>image.height)-(b.y0+b.y1>image.height))||a.x0-b.x0);
}
function isolated(image,p){
  const w=p.x1-p.x0,h=p.y1-p.y0,cv=createCanvas(w,h),c=cv.getContext('2d');c.drawImage(image,p.x0,p.y0,w,h,0,0,w,h);
  const core=new Uint8Array(w*h),horizontal=new Uint8Array(w*h),mask=new Uint8Array(w*h);
  for(const n of p.pixels)core[(Math.floor(n/image.width)-p.y0)*w+n%image.width-p.x0]=1;
  for(let y=0;y<h;y++){let count=0;for(let x=-7;x<w+7;x++){if(x+7<w&&x+7>=0)count+=core[y*w+x+7];if(x-8>=0&&x-8<w)count-=core[y*w+x-8];if(x>=0&&x<w)horizontal[y*w+x]=count>0;}}
  for(let x=0;x<w;x++){let count=0;for(let y=-7;y<h+7;y++){if(y+7<h&&y+7>=0)count+=horizontal[(y+7)*w+x];if(y-8>=0&&y-8<h)count-=horizontal[(y-8)*w+x];if(y>=0&&y<h)mask[y*w+x]=count>0;}}
  const data=c.getImageData(0,0,w,h);for(let i=0;i<mask.length;i++)if(!mask[i])data.data[i*4+3]=0;c.putImageData(data,0,0);return cv;
}
const metadata={};
for(const[kind,spec]of Object.entries(specs)){
  const image=await loadImage(spec.file),parts=components(image);if(parts.length!==spec.count)throw new Error(`${kind}: expected ${spec.count} components, got ${parts.length}`);
  const atlas=createCanvas(parts.reduce((sum,p)=>sum+p.x1-p.x0+6,0),Math.max(...parts.map(p=>p.y1-p.y0))+6),c=atlas.getContext('2d');let x=3;
  for(const p of parts){p.rect=[x,3,p.x1-p.x0,p.y1-p.y0];c.drawImage(isolated(image,p),x,3);x+=p.rect[2]+6;}
  const file=`assets/story/${kind}-components-v1.png`;await writeFile(file,atlas.toBuffer('image/png'));
  const legs=spec.legs.map(leg=>({...leg,upperJoints:leg.upperJoints.map(([x,y])=>[x-parts[leg.upperIndex].x0,y-parts[leg.upperIndex].y0]),lowerJoints:leg.lowerJoints.map(([x,y])=>[x-parts[leg.lowerIndex].x0,y-parts[leg.lowerIndex].y0])}));
  metadata[kind]={file,width:spec.width,height:spec.height,actorHeight:spec.actorHeight,body:spec.body,parts:parts.map(p=>p.rect),legs};
}
