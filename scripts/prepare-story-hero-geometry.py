def bake(id):
 stem=Path(f'assets/runtime/{id}-v{VERSIONS.get(id,1)}')
 meta=json.loads(stem.with_suffix('.json').read_text())
 image=Image.open(stem.with_suffix('.webp')).convert('RGBA')
 atlases={name:(image,profile) for name,profile in meta['atlases'].items()}
 if id in WALKS:
  stem=Path('assets/story')/WALKS[id]
  atlases['motion']=(Image.open(stem.with_suffix('.webp')).convert('RGBA'),{'scale':1,'frames':json.loads(stem.with_suffix('.json').read_text())})
 out={}
 for name,(image,profile) in atlases.items():
  for index,f in enumerate(profile['frames']):
   key=f'{name}:{index}'
   if not (name=='motion' and index<8) and key not in HANDS[id]: continue
   x,y,w,h=f['rect'];crop=image.crop((x,y,x+w,y+h));alpha=crop.getchannel('A');pixels=alpha.load()
   scale=f.get('scale',profile['scale']);anchor=f['anchor']-f['x']
   if name=='motion':
    # Register the mass of the pelvis, rather than the changing width of the
    # stride or a glove. Bound the correction so a coat cannot shift the root.
    points=[(xx,pixels[xx,yy]) for yy in range(round(h*.48),round(h*.62)) for xx in range(w) if pixels[xx,yy]>160]
    if points:
     centre=sum(xx*a for xx,a in points)/sum(a for _,a in points)
     anchor=max(anchor-18/scale,min(anchor+18/scale,centre))
   hand=HANDS[id].get(key,(.79,.30))
   hx,hy=hand[0]*w,hand[1]*h
   # A socket is inside the painted hand, not transparent atlas padding.
   if pixels[min(w-1,round(hx)),min(h-1,round(hy))]<100:
    choices=[((xx-hx)**2+(yy-hy)**2,xx,yy) for yy in range(max(0,int(hy)-18),min(h,int(hy)+19)) for xx in range(max(0,int(hx)-18),min(w,int(hx)+19)) if pixels[xx,yy]>160]
    if choices: _,hx,hy=min(choices)
   bands=[]
   for lo,hi in [(0,.24),(.24,.67),(.67,1)]:
    pts=[(xx,yy) for yy in range(round(h*lo),min(h,round(h*hi))) for xx in range(w) if pixels[xx,yy]>120]
    if pts:
     xs,ys=zip(*pts);left=min(xs);top=min(ys);right=max(xs)+1;bottom=max(ys)+1
     bands.append([round((left-anchor)*scale,5),round((f['bottom']-f['y']-top)*scale,5),round((right-left)*scale,5),round((bottom-top)*scale,5)])
   out[key]={'anchor':round(f['x']+anchor,6),'hand':[round((hx-anchor)*scale,6),round((hy+f['y']-f['bottom'])*scale,6)],'hurt':bands}
   if id=='marcos' and key=='combat:10':out[key]['handHidden']=True
 return out

data={id:bake(id) for id in HANDS}
