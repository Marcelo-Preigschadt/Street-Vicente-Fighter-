export const costumeAsset = (id, atlas, legacy) => COSTUME_LAYOUT[id]?.[atlas] ? `assets/${id}-${atlas}-costume-v1.webp` : legacy;

export function alignCostumeSheet(sheet, id, atlas) {
 const layout = COSTUME_LAYOUT[id]?.[atlas];
 if (!layout) return sheet;
 if (sheet.frames.length !== layout.anchors.length) throw new Error('Quantidade de poses do traje inválida.');
 sheet.scale = layout.scaleY / sheet.image.height;
 sheet.frames.forEach((frame, i) => { frame.anchor = layout.anchors[i] * sheet.image.width - frame.sx; delete frame.scale; });
 return sheet;
}
